// PS5 debug packages, write side. Ported from pearlxcore/ProsperoPkgTool (MIT),
// the engine behind its img_create (ProsperoDebugPackageBuilder), so that a
// package built here is byte-identical to one it builds with the same seed.
//
// Layers, bottom up (each in its own source file):
//   inner image   pfs_image.dat: file data first, then a block-info table and
//                 the metadata (a PFS-like file system with afids and flat
//                 path tables) in a PFSv3 container (fpkg_inner_build.cpp)
//   NAPS          naps_pkg_layout.dat, the inner image's block geometry
//   outer PFS     pfs_image.dat + NAPS in an AES-XTS-encrypted PFS
//   CNT, FIH, SI  the package container, header and install metadata
